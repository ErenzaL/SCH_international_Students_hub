-- AI Office pilot: privacy-preserving metrics (read-only, aggregates only).
-- Run with:  supabase db query --remote --read-only "$(cat docs/release/pilot-metrics.sql)"
-- No message text, names, e-mails or user ids are selected; groups with fewer than 5 items are suppressed (NULL).
-- Change the pilot window in `params` before running.
with params as (
  select timestamptz '2026-12-01 00:00+09' as since, timestamptz '2026-12-15 00:00+09' as until
),
answers as (
  select m.metadata, coalesce(jsonb_array_length(m.citations), 0) as n_citations
  from public.ai_messages m, params p
  where m.role = 'assistant' and m.created_at >= p.since and m.created_at < p.until
    and coalesce(m.metadata->>'kind', '') <> 'handoff_created'
),
tasks as (
  select t.agent_id, t.task_type, t.status, t.error_code, t.attempts,
         extract(epoch from (t.completed_at - t.created_at)) as seconds
  from public.agent_tasks t, params p
  where t.created_at >= p.since and t.created_at < p.until and t.requested_by is not null
),
tickets as (
  select t.status, t.language
  from public.support_tickets t, params p
  where t.created_at >= p.since and t.created_at < p.until
)
select 'chat' as area, 'answers' as metric, count(*)::text as value from answers
union all select 'chat', 'generated by the model (share)',
  case when count(*) >= 5 then round(avg((metadata->>'answer_generation' = 'llm')::int), 3)::text end from answers
union all select 'chat', 'fallback model used (share of model answers)',
  case when count(*) filter (where metadata->>'answer_generation' = 'llm') >= 5 then
    round(avg((metadata->>'fallback_used')::boolean::int) filter (where metadata->>'answer_generation' = 'llm'), 3)::text end
  from answers
union all select 'chat', 'answers with >= 1 citation (share)',
  case when count(*) >= 5 then round(avg((n_citations > 0)::int), 3)::text end from answers
union all select 'chat', 'insufficient evidence (share)',
  case when count(*) >= 5 then round(avg(coalesce((metadata->>'insufficient_evidence')::boolean, false)::int), 3)::text end
  from answers
union all select 'chat', 'human handoff offered (share)',
  case when count(*) >= 5 then round(avg(coalesce((metadata->>'offer_handoff')::boolean, false)::int), 3)::text end from answers
union all select 'chat', 'latency p50 / p90 (ms)',
  case when count(*) >= 5 then concat(
    percentile_cont(0.5) within group (order by (metadata->>'latency_ms')::numeric)::int, ' / ',
    percentile_cont(0.9) within group (order by (metadata->>'latency_ms')::numeric)::int) end
  from answers where metadata ? 'latency_ms'
union all select 'chat', 'model tokens input / output (sum)',
  concat(coalesce(sum((metadata->>'input_tokens')::bigint), 0), ' / ', coalesce(sum((metadata->>'output_tokens')::bigint), 0))
  from answers
union all select 'agents', 'tasks (signed-in students)', count(*)::text from tasks
union all select 'agents', 'completed (share)',
  case when count(*) >= 5 then round(avg((status = 'completed')::int), 3)::text end from tasks
union all select 'agents', 'failed (count)', count(*) filter (where status = 'failed')::text from tasks
union all select 'agents', 'retried (count)', count(*) filter (where attempts > 1)::text from tasks
union all select 'agents', 'duration p50 / p90 (s)',
  case when count(*) >= 5 then concat(
    round(percentile_cont(0.5) within group (order by seconds)::numeric, 1), ' / ',
    round(percentile_cont(0.9) within group (order by seconds)::numeric, 1)) end
  from tasks where seconds is not null
union all select 'agents', 'failures by error code',
  string_agg(concat(error_code, ': ', n), ', ') from (
    select error_code, count(*) n from tasks where status = 'failed' group by 1 having count(*) >= 1) e
union all select 'support', 'human support requests created', count(*)::text from tickets
union all select 'support', 'by language (groups >= 5)',
  string_agg(concat(language, ': ', n), ', ') from (select language, count(*) n from tickets group by 1 having count(*) >= 5) g
union all select 'support', 'resolved (share)',
  case when count(*) >= 5 then round(avg((status = 'resolved')::int), 3)::text end from tickets
union all select 'discovery', 'items sent to review / dismissed',
  concat(count(*) filter (where i.status = 'imported'), ' / ', count(*) filter (where i.status = 'dismissed'))
  from public.discovered_items i, params p where i.reviewed_at >= p.since and i.reviewed_at < p.until;
